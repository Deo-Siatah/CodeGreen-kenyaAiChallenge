export type Language = 'en' | 'sw';
export type TranslationKey = keyof typeof en;
export type TranslationVars = Record<string, string | number>;
export type Translator = (key: TranslationKey, vars?: TranslationVars) => string;

const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, sw };

export function translate(
  language: Language,
  key: TranslationKey,
  vars: TranslationVars = {},
): string {
  const dictionary = dictionaries[language];
  const count = typeof vars.count === 'number' ? vars.count : null;
  const pluralKey =
    count === null ? key : (`${key}${count === 1 ? '_one' : '_other'}` as TranslationKey);
  const template = dictionary[pluralKey] ?? dictionary[key];
  return template.replace(/\{\{(\w+)\}\}/g, (_match, name: string) =>
    String(vars[name] ?? ''),
  );
}

export function makeTranslator(language: Language): Translator {
  return (key, vars) => translate(language, key, vars);
}
